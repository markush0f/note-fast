export default function ItemIcon({
  icon,
  kind,
  size = 18,
  ...props
}: IconProps & { icon?: ItemIconId; kind: "note" | "notebook" }) {
  const id = isItemIconId(icon) ? icon : kind === "notebook" ? "book" : "page";
  const Icon = icons[id];
  return (
    <Icon
      width={size}
      height={size}
      strokeWidth={1.5}
      aria-hidden="true"
      focusable="false"
      data-item-icon={id}
      {...props}
    />
  );
}
